            background = MedicalTools.roundBg("#E0F2F1", 18f, "#80CBC4")
            setTextColor(Color.BLACK)
            setHintTextColor(Color.parseColor("#546E7A"))
        }
        root.addView(searchInp)

        val listView = ListView(context).apply {
            layoutParams = LinearLayout.LayoutParams(-1, 0, 1f)
            isNestedScrollingEnabled = true
            divider = null
            dividerHeight = 12
            setPadding(0, 14, 0, 0)
        }
        root.addView(listView)

        fun renderList() {
            val q = searchInp.text.toString().trim().lowercase()
            val source = if (tabIdx == 0) smpDrugsList else cardWritingGuides
            val filtered = source.filter {
                q.isEmpty() || it.title.lowercase().contains(q) || it.subtitle.lowercase().contains(q) || it.content.lowercase().contains(q)
            }
            val display = filtered.map { "${it.title}\n• ${it.subtitle}" }
            listView.adapter = object : ArrayAdapter<String>(context, android.R.layout.simple_list_item_1, display) {
                override fun getView(position: Int, convertView: View?, parent: ViewGroup): View = (super.getView(position, convertView, parent) as TextView).apply {
                    setPadding(26, 20, 26, 20)
                    setTextColor(Color.parseColor("#263238"))
                    textSize = 14f
                    setLineSpacing(5f, 1.15f)
                    background = MedicalTools.roundBg("#F2F9F9", 16f, "#B2DFDB")
                }
            }
            listView.setOnItemClickListener { _, _, pos, _ ->
                val item = filtered[pos]
                MedicalTools.showDetailDialog(context, item.title, item.content, "#00695C")
            }
        }

        fun drawTabs() {
            tabRow.removeAllViews()
            listOf("💊 Препараты СМП (${smpDrugsList.size})", "✍️ Оформление карты и Осмотр (${cardWritingGuides.size})").forEachIndexed { i, title ->
                val sel = i == tabIdx
                tabRow.addView(TextView(context).apply {
                    text = title; textSize = 12.5f; gravity = Gravity.CENTER
                    typeface = if (sel) Typeface.DEFAULT_BOLD else Typeface.DEFAULT
                    setTextColor(if (sel) Color.WHITE else Color.parseColor("#004D40"))
                    setPadding(16, 14, 16, 14)
                    background = MedicalTools.roundBg(if (sel) "#00796B" else "#E0F2F1", 14f)
                    layoutParams = LinearLayout.LayoutParams(0, -2, 1f).apply { rightMargin = if (i == 0) 8 else 0 }
                    setOnClickListener { tabIdx = i; drawTabs(); renderList() }
                })
            }
        }

        searchInp.addTextChangedListener(object : TextWatcher {
            override fun afterTextChanged(s: Editable?) = renderList()
            override fun beforeTextChanged(s: CharSequence?, start: Int, count: Int, after: Int) {}
            override fun onTextChanged(s: CharSequence?, start: Int, count: Int, after: Int) {}
        })

        drawTabs()
        renderList()
        bottomSheet.show()
    }
