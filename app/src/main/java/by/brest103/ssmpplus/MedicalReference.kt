    fun showOrdersAndProtocolsSheet(context: Context) {
        val (bottomSheet, root) = MedicalTools.createBaseSheet(
            context,
            "📜 ТЛТ И ПРИКАЗЫ (${mzrbOrders.size})",
            "#37474F",
            fullHeight = true
        )

        val searchInp = EditText(context).apply {
            hint = "Поиск: ТЛТ, ЧКВ, ОНМК, №179, №99, анафилаксия, психиатрия, дети..."
            setPadding(30, 20, 30, 20)
            background = MedicalTools.roundBg("#ECEFF1", 18f, "#CFD8DC")
            setTextColor(Color.BLACK)
            setHintTextColor(Color.parseColor("#546E7A"))
        }
        root.addView(searchInp)

        var activeCategory = "Все"
        val countText = TextView(context).apply {
            textSize = 12f
            setTextColor(Color.parseColor("#546E7A"))
            setPadding(26, 10, 26, 2)
        }
        root.addView(countText)

        val listView = ListView(context).apply {
            layoutParams = LinearLayout.LayoutParams(-1, 0, 1f)
            isNestedScrollingEnabled = true
            divider = null
            dividerHeight = 12
            setPadding(0, 14, 0, 0)
        }
        root.addView(listView)

        fun renderList(q: String) {
            val query = q.trim().lowercase()
            val filtered = mzrbOrders.filter {
                (activeCategory == "Все" || it.category == activeCategory) &&
                    (query.isEmpty() || it.title.lowercase().contains(query) ||
                        it.subtitle.lowercase().contains(query) || it.content.lowercase().contains(query) ||
                        it.category.lowercase().contains(query))
            }
            countText.text = "Найдено: ${filtered.size} из ${mzrbOrders.size}"
            val display = filtered.map { "${it.title}\n• ${it.subtitle}\n• ${it.category}" }
            listView.adapter = object : ArrayAdapter<String>(context, android.R.layout.simple_list_item_1, display) {
                override fun getView(position: Int, convertView: View?, parent: ViewGroup): View = (super.getView(position, convertView, parent) as TextView).apply {
                    setPadding(26, 20, 26, 20)
                    setTextColor(Color.parseColor("#263238"))
                    textSize = 13.5f
                    setLineSpacing(5f, 1.15f)
                    background = MedicalTools.roundBg("#F5F7F8", 16f, "#CFD8DC")
                }
            }
            listView.setOnItemClickListener { _, _, pos, _ ->
                val item = filtered[pos]
                val hasPdf = item.pdfPath.isNotBlank()
                MedicalTools.showDetailDialog(
                    context, item.title, item.content, "#37474F",
                    actionLabel = if (hasPdf) "📄 PDF протокола" else null,
                    onAction = if (hasPdf) { { MzrbCatalog.openPdf(context, item.title, item.pdfPath) } } else null
                )
            }
        }

        // Фильтр по разделам. Объявлен после renderList, чтобы не было forward reference.
        val categories = listOf("Все") + mzrbOrders.map { it.category }.distinct().sorted()
        val chips = mutableListOf<Pair<TextView, String>>()
        val chipsRow = LinearLayout(context).apply { orientation = LinearLayout.HORIZONTAL }
        fun updateChips() {
            chips.forEach { (chip, cat) ->
                val on = cat == activeCategory
                chip.setTextColor(Color.parseColor(if (on) "#FFFFFF" else "#37474F"))
                chip.background = MedicalTools.roundBg(if (on) "#37474F" else "#ECEFF1", 14f, "#CFD8DC")
            }
        }
        categories.forEach { cat ->
            val chip = TextView(context).apply {
                text = cat
                textSize = 12.5f
                typeface = Typeface.DEFAULT_BOLD
                setPadding(20, 12, 20, 12)
                setOnClickListener {
                    activeCategory = cat
                    updateChips()
                    renderList(searchInp.text.toString())
                }
            }
            chips.add(chip to cat)
            chipsRow.addView(chip)
        }
        root.addView(HorizontalScrollView(context).apply { addView(chipsRow) }, 1)
        updateChips()

        searchInp.addTextChangedListener(object : TextWatcher {
            override fun afterTextChanged(s: Editable?) = renderList(s.toString())
            override fun beforeTextChanged(s: CharSequence?, start: Int, count: Int, after: Int) {}
            override fun onTextChanged(s: CharSequence?, start: Int, count: Int, before: Int, after: Int) {}
        })

        renderList("")
        bottomSheet.show()
    }

